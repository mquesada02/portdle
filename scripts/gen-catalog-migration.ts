import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { SCHEDULE_EPOCH } from "../src/engine/schedule-gen.ts";
import { SWITCH_OVER_DAY } from "../src/engine/switch-over.ts";
import {
	type CatalogEntry,
	DAILY_CATEGORIES,
	type DailyCategory,
	type ScheduleFile,
} from "../src/engine/types.ts";
import { addUtcDays, utcDayIndex } from "../src/engine/utc.ts";

// Writes the one generated migration: public.switch_over_day() and the
// import of the catalog and the Schedule from the committed files, from the
// epoch through the switch-over day. `--check` fails when the committed file
// differs from what this script would write.

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const migrationPath = join(
	root,
	"supabase/migrations/20261001000009_catalog_schedule_import.sql",
);

type Input = {
	protocols: CatalogEntry[];
	applications: CatalogEntry[];
	schedules: Record<DailyCategory, ScheduleFile>;
	switchOverDay: string;
};

export function sqlText(value: string): string {
	return `'${value.replaceAll("'", "''")}'`;
}

function sqlNullableText(value: string | undefined): string {
	return value === undefined ? "null" : sqlText(value);
}

function sqlTextArray(values: string[] | undefined): string {
	if (!values || values.length === 0) {
		return "'{}'::text[]";
	}
	return `array[${values.map(sqlText).join(", ")}]::text[]`;
}

function sqlJsonArray(values: unknown[] | undefined): string {
	return `${sqlText(JSON.stringify(values ?? []))}::jsonb`;
}

function entryRow(entry: CatalogEntry, kind: string): string {
	return `\t(${[
		sqlText(entry.id),
		sqlText(kind),
		sqlText(entry.name),
		sqlTextArray(entry.aliases),
		String(entry.port),
		sqlText(entry.transport),
		sqlText(entry.description),
		sqlNullableText(entry.blurb),
		String(entry.answerEligible),
		String(entry.retired ?? false),
		sqlJsonArray(entry.sources),
	].join(", ")})`;
}

function scheduleRows(
	category: DailyCategory,
	schedule: ScheduleFile,
	catalogIds: Set<string>,
	switchOverDay: string,
): string[] {
	if (schedule.epoch !== SCHEDULE_EPOCH) {
		throw new Error(
			`${category} schedule epoch ${schedule.epoch} is not ${SCHEDULE_EPOCH}`,
		);
	}
	const lastIndex = utcDayIndex(switchOverDay, SCHEDULE_EPOCH);
	const rows: string[] = [];
	for (let index = 0; index <= lastIndex; index += 1) {
		const day = addUtcDays(SCHEDULE_EPOCH, index);
		const cycle = schedule.cycles.find(
			(candidate) =>
				candidate.startDay <= index &&
				index < candidate.startDay + candidate.order.length,
		);
		if (!cycle) {
			throw new Error(`${category}: no cycle covers ${day}`);
		}
		const id = cycle.order[index - cycle.startDay];
		if (id === undefined || !catalogIds.has(id)) {
			throw new Error(`${category}: ${day} names unknown entry ${id}`);
		}
		rows.push(
			`\t(${sqlText(category)}, ${sqlText(day)}, ${sqlText(id)}, ${sqlText(
				addUtcDays(SCHEDULE_EPOCH, cycle.startDay),
			)})`,
		);
	}
	return rows;
}

export function buildMigration(input: Input): string {
	const entries = [
		...input.protocols.map((entry) => entryRow(entry, "protocol")),
		...input.applications.map((entry) => entryRow(entry, "application")),
	];
	const catalogIds = new Set(
		[...input.protocols, ...input.applications].map((entry) => entry.id),
	);
	const schedule = DAILY_CATEGORIES.flatMap((category) =>
		scheduleRows(
			category,
			input.schedules[category],
			catalogIds,
			input.switchOverDay,
		),
	);
	return `-- GENERATED by scripts/gen-catalog-migration.ts from the switch-over day in
-- src/engine/switch-over.ts and the committed catalog and schedule files. Do
-- not edit by hand: run \`pnpm gen:catalog-migration\` again. Apply in the
-- Supabase SQL editor after 20261001000008 (the owner applies migrations in
-- filename order). It runs before the triggers migration, so the triggers
-- need no exception for the import.
--
-- public.switch_over_day() is the one place the switch-over day lives in SQL;
-- every later rule that depends on it calls this function. Spec 5: the Daily
-- of every day on or before it keeps the answer the committed schedule gave.

create function public.switch_over_day()
returns date
language sql
immutable
set search_path = ''
as $$ select date ${sqlText(input.switchOverDay)} $$;

revoke all on function public.switch_over_day() from public, anon, authenticated;
grant execute on function public.switch_over_day() to schedule_generator;

insert into public.catalog_entries (id, kind, name, aliases, port, transport, description, blurb, answer_eligible, retired, sources) values
${entries.join(",\n")};

insert into public.schedule (category, day, entry_id, cycle_start) values
${schedule.join(",\n")};
`;
}

function readJson<T>(path: string): T {
	return JSON.parse(readFileSync(path, "utf8")) as T;
}

export function readInputs(): Input {
	const catalogs = join(root, "src/catalogs");
	return {
		protocols: readJson(join(catalogs, "protocols.json")),
		applications: readJson(join(catalogs, "applications.json")),
		schedules: {
			mixed: readJson(join(catalogs, "schedules/mixed.json")),
			protocols: readJson(join(catalogs, "schedules/protocols.json")),
			applications: readJson(join(catalogs, "schedules/applications.json")),
		},
		switchOverDay: SWITCH_OVER_DAY,
	};
}

if (
	process.argv[1] &&
	import.meta.url === pathToFileURL(process.argv[1]).href
) {
	const next = buildMigration(readInputs());
	if (process.argv.includes("--check")) {
		if (readFileSync(migrationPath, "utf8") !== next) {
			console.error(
				"The generated catalog migration is out of date: run pnpm gen:catalog-migration.",
			);
			process.exitCode = 1;
		}
	} else {
		writeFileSync(migrationPath, next);
	}
}
